// WriteEquate writes an EQU directive
func (aw *ASMWriter) WriteEquate(name string, value interface{}) error {
	var valueStr string
	switch v := value.(type) {
	case int:
		valueStr = fmt.Sprintf("#%04X", v)
	case uint16:
		valueStr = fmt.Sprintf("#%04X", v)
	case string:
		valueStr = v
	default:
		valueStr = fmt.Sprintf("%v", v)
	}

	_, err := fmt.Fprintf(aw.w, "%s\tEQU\t%s\n", name, valueStr)
	return err
}

// WriteBlankLine writes a blank line
func (aw *ASMWriter) WriteBlankLine() error {
	_, err := aw.w.Write([]byte("\n"))
	return err
}

// WriteRawLine writes a raw line of text
func (aw *ASMWriter) WriteRawLine(line string) error {
	_, err := fmt.Fprintf(aw.w, "%s\n", line)
	return err
}