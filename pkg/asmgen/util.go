// WriteDBWithLabels generates DB directives with labeled sections
func (aw *ASMWriter) WriteDBWithLabels(data []byte, lineLength, sectionLines int, labelPrefix string, withSize bool) error {
	if len(data) == 0 {
		return nil
	}

	lineCount := 0
	labelIndex := 0

	// Write initial label if prefix provided and section lines > 0
	if labelPrefix != "" && sectionLines > 0 {
		if err := aw.WriteLabel(fmt.Sprintf("%s%02d", labelPrefix, labelIndex)); err != nil {
			return err
		}
		labelIndex++
	}

	for i := 0; i < len(data); i += lineLength {
		end := i + lineLength
		if end > len(data) {
			end = len(data)
		}

		var line strings.Builder
		line.WriteString("#")
		line.WriteString(fmt.Sprintf("%02X", data[i]))

		for j := i + 1; j < end; j++ {
			line.WriteString(",#")
			line.WriteString(fmt.Sprintf("%02X", data[j]))
		}

		if err := aw.WriteInstruction("DB", line.String(), ""); err != nil {
			return err
		}

		lineCount++

		// Check if we need a new label
		if sectionLines > 0 && lineCount >= sectionLines && i < len(data)-lineLength {
			lineCount = 0
			if labelPrefix != "" {
				if err := aw.WriteLabel(fmt.Sprintf("%s%02d", labelPrefix, labelIndex)); err != nil {
					return err
				}
				labelIndex++
			}
		}
	}

	if withSize {
		if err := aw.WriteComment(fmt.Sprintf("Total size %d bytes", len(data))); err != nil {
			return err
		}
	}

	return nil
}

